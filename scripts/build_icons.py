"""Generate the console's service icons: a rounded tile per service, coloured by category, with a
monogram in the project's pixel font. Entirely original - no third-party artwork.

    uv run python scripts/build_icons.py          # after scripts/build_service_catalog.py

Reads src/emulator_ui/catalog.json, writes ui/public/icons/<service>.svg (and removes stale icons).
Monograms are derived from botocore's serviceId (acronyms, camel-case/word initials); overrides live in
scripts/catalog_overrides.json under "monograms". Every service gets a unique monogram.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from pixelfont import FONT, GLYPH_HEIGHT, text_cells

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "src" / "emulator_ui" / "catalog.json"
OVERRIDES = Path(__file__).with_name("catalog_overrides.json")
ICONS_OUT = ROOT / "ui" / "public" / "icons"
MARKER = "generated by scripts/build_icons.py"

# Our own palette (one hue per category); tiles get a subtle top-to-bottom gradient.
CATEGORY_COLORS = {
    "Analytics": "#7b61ff",
    "Application Integration": "#d6457a",
    "Artificial Intelligence": "#1aa38f",
    "Blockchain": "#b0782e",
    "Business Applications": "#c0392b",
    "Cloud Financial Management": "#3f9b4a",
    "Compute": "#e07b24",
    "Containers": "#d35d2b",
    "Customer Enablement": "#2f78c4",
    "Databases": "#3456c7",
    "Developer Tools": "#4a5bd1",
    "End User Computing": "#239a8a",
    "Front-End Web & Mobile": "#c23a5e",
    "Games": "#8c4fd6",
    "Internet of Things": "#3a9a3f",
    "Management Tools": "#c2338a",
    "Marketplace": "#596275",
    "Media Services": "#d9603b",
    "Migration & Modernization": "#21948c",
    "Networking & Content Delivery": "#7552d9",
    "Quantum Technologies": "#c7861a",
    "Satellite": "#3b6fd1",
    "Security, Identity & Compliance": "#cf3f3f",
    "Storage": "#4c9a2a",
    "Other": "#5c6275",
}
NOISE_WORDS = {"service", "services", "the", "for", "and", "of", "amazon", "aws"}


def _lighten(hex_color: str, amount: float) -> str:
    r, g, b = (int(hex_color[i : i + 2], 16) for i in (1, 3, 5))
    r, g, b = (round(c + (255 - c) * amount) for c in (r, g, b))
    return f"#{r:02x}{g:02x}{b:02x}"


def _tokens(service_id: str) -> list[str]:
    """'CloudWatch Logs' -> ['Cloud', 'Watch', 'Logs']; 'DynamoDB' -> ['Dynamo', 'DB']; 'EC2' -> ['EC2']."""
    words = [w for w in re.split(r"[\s\-_./]+", service_id) if w and w.lower() not in NOISE_WORDS]
    out: list[str] = []
    for word in words:
        out += re.findall(r"[A-Z]+[0-9]*(?![a-z])|[A-Z]?[a-z]+[0-9]*|[0-9]+", word) or [word]
    return out


def candidates(service_id: str, service: str) -> list[str]:
    """Monogram candidates, best first (all upper-case, 2-4 characters, A-Z/0-9 only)."""
    toks = _tokens(service_id)
    acronym = lambda t: t.isupper() or t.isdigit()  # noqa: E731
    out: list[str] = []
    if len(toks) == 1 and acronym(toks[0]) and len(toks[0]) <= 4:
        out.append(toks[0])  # SQS, IAM, EC2, S3, SFN
    initials = "".join(t if acronym(t) and len(t) <= 3 else t[0] for t in toks).upper()
    if len(initials) >= 2:
        out.append(initials[:4])
    first = toks[0] if toks else service
    consonants = first[0] + re.sub(r"[aeiouAEIOU]", "", first[1:])
    out += [consonants[:3].upper(), first[:3].upper(), (initials + consonants[1:])[:4].upper()]
    base = re.sub(r"[^A-Za-z0-9]", "", service).upper()
    out += [base[:4], base[:2] + base[-2:]]
    out += [f"{(initials or base)[:3]}{d}" for d in range(2, 10)]
    clean = []
    for c in out:
        c = re.sub(r"[^A-Z0-9]", "", c.upper())
        if 2 <= len(c) <= 4 and all(ch in FONT for ch in c) and c not in clean:
            clean.append(c)
    return clean


def assign_monograms(services: list[dict], overrides: dict[str, str]) -> dict[str, str]:
    taken: dict[str, str] = {}
    result: dict[str, str] = {}
    for svc in sorted(services, key=lambda s: (s["id"] not in overrides, s["id"])):  # overrides first
        if svc["id"] in overrides:
            mono = overrides[svc["id"]].upper()
        else:
            mono = next(c for c in candidates(svc["serviceId"], svc["id"]) if c not in taken)
        if mono in taken:
            raise SystemExit(f"monogram {mono} used by both {taken[mono]} and {svc['id']}")
        taken[mono] = svc["id"]
        result[svc["id"]] = mono
    return result


def icon_svg(mono: str, color: str, title: str) -> str:
    size, max_w, max_h = 64, 50, 30
    cells, width = text_cells(mono)
    px = max(1, min(max_w // width, max_h // GLYPH_HEIGHT))
    tw, th = width * px, GLYPH_HEIGHT * px
    ox, oy = (size - tw) // 2, (size - th) // 2
    rects = "".join(
        f'<rect x="{ox + x * px}" y="{oy + y * px}" width="{px}" height="{px}"/>' for x, y in cells
    )
    return (
        f"<!-- {MARKER} -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}" '
        f'role="img" aria-label="{title}">'
        f"<title>{title}</title>"
        f'<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="{_lighten(color, 0.18)}"/><stop offset="1" stop-color="{color}"/>'
        f"</linearGradient></defs>"
        f'<rect width="{size}" height="{size}" rx="13" fill="url(#g)"/>'
        f'<g fill="#ffffff" shape-rendering="crispEdges">{rects}</g>'
        f"</svg>\n"
    )


def main() -> int:
    services = json.loads(CATALOG.read_text())["services"]
    overrides = json.loads(OVERRIDES.read_text()).get("monograms", {})
    monograms = assign_monograms(services, overrides)
    ICONS_OUT.mkdir(parents=True, exist_ok=True)
    wanted = {f"{s['id']}.svg" for s in services}
    for stale in ICONS_OUT.glob("*.svg"):
        if stale.name not in wanted:
            stale.unlink()
    for svc in services:
        color = CATEGORY_COLORS.get(svc["category"], CATEGORY_COLORS["Other"])
        title = svc["fullName"].replace("&", "&amp;").replace("<", "&lt;").replace('"', "&quot;")
        (ICONS_OUT / f"{svc['id']}.svg").write_text(icon_svg(monograms[svc["id"]], color, title))
    sample = {
        k: monograms[k] for k in ("dynamodb", "s3", "lambda", "sqs", "events", "stepfunctions", "iam", "ec2")
    }
    print(f"{len(services)} icons -> {ICONS_OUT.relative_to(ROOT)}; e.g. {sample}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
