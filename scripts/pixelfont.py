GLYPH_HEIGHT = 7


def text_cells(text: str, gap: int = 1) -> tuple[list[tuple[int, int]], int]:
    """Lit pixel coordinates for `text` and its width in pixels (height is GLYPH_HEIGHT)."""
    cells: list[tuple[int, int]] = []
    x = 0
    for ch in text.upper():
        glyph = FONT[ch]
        for row, bits in enumerate(glyph):
            cells += [(x + col, row) for col, bit in enumerate(bits) if bit == "1"]
        x += len(glyph[0]) + gap
    return cells, max(0, x - gap)
