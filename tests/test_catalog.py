"""Catalog + icon integrity, including the licensing rules: only generated, first-party artwork ships."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = json.loads((ROOT / "src" / "emulator_ui" / "catalog.json").read_text())["services"]
ICONS = ROOT / "ui" / "public" / "icons"
MARKER = "generated by scripts/build_icons.py"


def test_every_service_has_a_generated_icon_and_category() -> None:
    assert len(CATALOG) == 436
    for svc in CATALOG:
        assert svc["icon"] == f"icons/{svc['id']}.svg"
        assert (ICONS / f"{svc['id']}.svg").is_file(), svc["id"]
        assert svc["category"] and svc["category"] != "Other", svc["id"]
    assert {p.stem for p in ICONS.glob("*.svg")} == {s["id"] for s in CATALOG}  # no stray icons


def test_icons_are_first_party_svgs() -> None:
    for path in ICONS.glob("*.svg"):
        text = path.read_text()
        assert MARKER in text, path.name
        assert not re.search(r"<image\b|xlink:href|href=|https?://(?!www\.w3\.org)", text), path.name


def test_monograms_are_unique_and_short() -> None:
    monograms = {}
    for path in ICONS.glob("*.svg"):
        title = re.search(r"<title>(.*?)</title>", path.read_text())
        assert title, path.name
    # Uniqueness is enforced at build time; re-derive to make sure overrides didn't collide.
    import sys

    sys.path.insert(0, str(ROOT / "scripts"))
    from build_icons import assign_monograms

    overrides = json.loads((ROOT / "scripts" / "catalog_overrides.json").read_text())["monograms"]
    monograms = assign_monograms(CATALOG, overrides)
    assert len(set(monograms.values())) == len(CATALOG)
    assert all(1 <= len(m) <= 4 for m in monograms.values())


def test_no_aws_artwork_or_marks_in_shipped_assets() -> None:
    assert not (ROOT / "ui" / "public" / "aws-icons").exists()
    names = [p.name for p in (ROOT / "ui" / "public").rglob("*")] + [
        p.name for p in (ROOT / "assets").rglob("*")
    ]
    assert not any("aws" in n.lower() for n in names)
    for path in (ROOT / "assets" / "brand").rglob("*.svg"):
        assert "AWS" not in path.read_text(), f"AWS mark in image {path.name}"
    assert "AWS" not in (ROOT / "ui" / "public" / "logo.svg").read_text()
